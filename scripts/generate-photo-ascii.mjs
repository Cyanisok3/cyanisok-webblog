import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ids = ['zibo', 'shanghai', 'hainan', 'yantai', 'ningbo', 'unnc', 'aquarium'];
const ramp = ' .:-=+*#%@';
const width = 40;
const entries = [];

for (const id of ids) {
  const input = path.join(process.cwd(), 'public', 'resources', 'monochrome', `${id}.webp`);
  const metadata = await sharp(input).metadata();
  const height = Math.max(8, Math.round(width * (metadata.height / metadata.width) * 0.60));
  const { data } = await sharp(input).greyscale().linear(1.12, -12).resize(width, height, { fit: 'fill' }).raw().toBuffer({ resolveWithObject: true });
  const rows = [];
  for (let y = 0; y < height; y += 1) {
    let row = '';
    for (let x = 0; x < width; x += 1) row += ramp[Math.round((data[y * width + x] / 255) * (ramp.length - 1))];
    rows.push(row.trimEnd());
  }
  entries.push(`  ${JSON.stringify(id)}: ${JSON.stringify(rows.join('\n'))},`);
}

const output = `// Generated by scripts/generate-photo-ascii.mjs\nexport const photoAscii: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
await writeFile(path.join(process.cwd(), 'lib', 'photo-ascii.ts'), output);
